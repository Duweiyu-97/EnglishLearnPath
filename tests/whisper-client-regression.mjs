import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../app/whisper.js', import.meta.url), 'utf8');
let respond;
const context = vm.createContext({window:{}, AbortController, setTimeout, clearTimeout, Blob, fetch: (...args) => respond(...args)});
vm.runInContext(source, context);
const client = context.window.localWhisper;
respond = async () => { throw new TypeError('Failed to fetch'); };
assert.match((await client.status()).error, /WHISPER_CONNECTION/);
respond = async () => ({ok:false, status:503});
assert.match((await client.status()).error, /WHISPER_HTTP_503/);
respond = async () => ({ok:true, json:async () => {throw new SyntaxError('HTML');}});
assert.match((await client.status()).error, /WHISPER_RESPONSE/);
respond = async () => ({ok:true, json:async () => ({})});
assert.match((await client.status()).error, /WHISPER_RESPONSE/);
respond = async () => ({ok:true, json:async () => ({ready:false,error:'[WHISPER_MODEL_MISSING] model missing'})});
assert.match((await client.status()).error, /WHISPER_MODEL_MISSING/);
respond = async () => ({ok:true, json:async () => ({ready:true,version:'test',platform:'windows/amd64'})});
assert.equal((await client.status()).ready, true);
console.log('Whisper client connection, HTTP, malformed response and recovery checks passed.');
